#!/usr/bin/env bash
# fm-safe-agent-crew.sh - the safe-agent harness launch driver (crewmate/scout).
#
# The safe-agent harness runs a firstmate crewmate or scout inside an OpenShell
# sandbox (the safe local coding agent stack, OpenShell >= 0.1.10 under colima).
# bin/fm-spawn.sh types this driver into the task pane as the launch command;
# the driver dispatches the crew into the sandbox and then keeps the pane
# foreground on the streamed crew session (`sandbox exec --tty`), so the pane
# stays alive and readable exactly like a TUI harness pane while the crew works.
#
# The isolation reference is the launcher's sandbox dispatch backend
# (projects/safe-local-coding-agent launcher/firstmate/backends/sandbox.sh, the
# archived firstmate commit "feat(backends): wire the experimental sandbox
# dispatch backend end to end"); this driver re-expresses that dispatch as a
# standard harness launch (captain ruling 2026-11-26): firstmate owns the task
# worktree, the backend owns the pane, and the sandbox is the crew's runtime.
#
# Modes:
#   fm-safe-agent-crew.sh verify              installation check: openshell on
#                                             PATH, version >= 0.1.10, gateway
#                                             connected. Actionable error
#                                             otherwise. fm-spawn runs this at
#                                             preflight; launch re-runs it.
#   fm-safe-agent-crew.sh config-get KEY      print one FM_BACKEND_SANDBOX_*
#                                             value (live env, then the
#                                             bootstrap env file, then empty).
#   fm-safe-agent-crew.sh launch <label> <worktree>
#                                             dispatch the crew. <label> is the
#                                             task label (fm-<id>); <worktree>
#                                             the task worktree to bind. The
#                                             boot record
#                                             <exchange>/<label>/boot.md must
#                                             already exist (bin/fm-spawn.sh
#                                             writes it before launch).
#   fm-safe-agent-crew.sh stop <label>        idempotent sandbox delete - the
#                                             control plane's stop primitive
#                                             for this harness (the exec dies
#                                             with its sandbox; the pane drops
#                                             back to its shell).
#   fm-safe-agent-crew.sh state <label>       recovery-grade crew state:
#                                             alive|dead|missing|unreadable.
#                                             A gateway that cannot answer is
#                                             `unreadable`, never inferred
#                                             absence.
#
# The script is source-safe: sourced, it only defines the fm_safe_agent_*
# functions (bin/fm-busy-lib.sh and bin/fm-task-inbox-lib.sh source it for the
# exchange-root read); invoked, it runs the mode.
#
# Configuration is the launcher bootstrap's env file
# (config/safe-agent-sandbox-env, written by `safe-agent firstmate`; values
# derived from the validated safe-agent.toml). Every value can be overridden by
# the environment for testing (FM_BACKEND_SANDBOX_<KEY>). Required for launch:
# IMAGE, POLICY, EXCHANGE_ROOT, SCRATCH_ROOT; the crew runtime permission
# profile config/safe-agent-crew-mimocode.json is required too (the
# zero-prompt posture). Missing values refuse with that remediation.
#
# The in-sandbox crew runtime is the delegate image's headless form
# `mimo run --format <fmt> "<prompt>"`, one run per record: the boot record is
# the boot prompt, and every steering record the exchange inbox accumulates
# becomes one follow-up run (bin/fm-safe-agent-crew-boot.sh owns the in-sandbox
# protocol; the exchange record formats it and the driver share are documented
# in .agents/skills/harness-adapters/references/harness/safe-agent.md).
#
# Git inside the sandbox: a linked worktree's `.git` file names a gitdir that
# lives outside the worktree bind, so the driver binds the owning repository's
# git dir at /sandbox/gitcommon and the boot wrapper exports
# GIT_DIR/GIT_COMMON_DIR/GIT_WORK_TREE from create-time env (plus
# safe.directory=* through GIT_CONFIG_*), so commits the crew makes through the
# binds are the host worktree's own commits. Pushing is a documented pending
# limitation: no forge credential is injected inside the sandbox yet.
#
# The crew policy (generated by `safe-agent up`) must declare every bind
# target read_write - /sandbox/worktree/<label>, /sandbox/exchange,
# /sandbox/scratch, and /sandbox/gitcommon. The first three are the launcher's
# T14 set; /sandbox/gitcommon is this adapter's addition and a policy that
# omits it makes the create refuse loudly (the gateway names the refused
# mount target) - add it to the crew policy and re-run `safe-agent up`.

# Every `sh -c` script below is single-quoted on purpose: its values are
# passed as positional arguments after the script text ("$0"/"$1") so no host
# value is ever spliced into the child shell's source.
# shellcheck disable=SC2016
# Source-safe preamble: resolve the script's own directory without side
# effects on source.
_FM_SAFE_AGENT_LIB_DIR=${BASH_SOURCE[0]%/*}
[ "$_FM_SAFE_AGENT_LIB_DIR" != "${BASH_SOURCE[0]}" ] || _FM_SAFE_AGENT_LIB_DIR=.

# The floor is the version the local stack was validated on (OpenShell v0.1.10,
# data/openshell-colima-retest/report.md): the colima reconcile race of the
# 0.1.6 era is fixed there. A missing or older CLI refuses loudly: the sandbox
# is the containment boundary, and an older one is not the validated stack.
FM_SAFE_AGENT_MIN_OPENSHELL_VERSION=0.1.10

FM_SAFE_AGENT_NAME_MAX=19

fm_safe_agent_home() {
  if [ -n "${FM_HOME:-}" ]; then
    printf '%s\n' "$FM_HOME"
    return 0
  fi
  (cd "${_FM_SAFE_AGENT_LIB_DIR:-.}/.." && pwd)
}

fm_safe_agent_env_file() {
  if [ -n "${FM_SAFE_AGENT_ENV_FILE:-}" ]; then
    printf '%s\n' "$FM_SAFE_AGENT_ENV_FILE"
    return 0
  fi
  printf '%s/config/safe-agent-sandbox-env\n' "$(fm_safe_agent_home)"
}

# fm_safe_agent_config_get KEY [DEFAULT] - the live environment wins
# (FM_BACKEND_SANDBOX_<KEY>), then the bootstrap env file, then DEFAULT. The
# env file is firstmate-owned (written by `safe-agent firstmate`) and only
# FM_BACKEND_SANDBOX_* names are read from it.
fm_safe_agent_config_get() {  # <key> [default]
  local key=$1 default=${2:-} file value
  eval "value=\${FM_BACKEND_SANDBOX_${key}:-}"
  if [ -n "$value" ]; then
    printf '%s\n' "$value"
    return 0
  fi
  file=$(fm_safe_agent_env_file)
  if [ -f "$file" ]; then
    # shellcheck disable=SC1090
    . "$file"
    eval "value=\${FM_BACKEND_SANDBOX_${key}:-}"
    if [ -n "$value" ]; then
      printf '%s\n' "$value"
      return 0
    fi
  fi
  [ -n "$default" ] && printf '%s\n' "$default"
  return 0
}

fm_safe_agent_openshell() {
  fm_safe_agent_config_get OPENSHELL openshell
}

# fm_safe_agent_version_at_least <candidate> <floor>: numeric dotted-release
# comparison. 0 candidate >= floor, 1 candidate < floor, 2 unparseable.
fm_safe_agent_version_at_least() {
  local candidate=${1:-} floor=${2:-} c f
  candidate=${candidate%%[-+]*}
  case "$candidate" in ''|*[!0-9.]*) return 2 ;; esac
  while [ -n "$floor" ]; do
    c=${candidate%%.*}
    f=${floor%%.*}
    [ -n "$c" ] || c=0
    [ "$c" -gt "$f" ] 2>/dev/null && return 0
    [ "$c" -lt "$f" ] 2>/dev/null && return 1
    case "$candidate" in *.*) candidate=${candidate#*.} ;; *) candidate= ;; esac
    case "$floor" in *.*) floor=${floor#*.} ;; *) floor= ;; esac
  done
  return 0
}

# fm_safe_agent_tool_check: refuse loudly if openshell is missing.
fm_safe_agent_tool_check() {
  local bin
  bin=$(fm_safe_agent_openshell)
  command -v "$bin" >/dev/null 2>&1 || {
    echo "error: the safe-agent harness requires the openshell CLI ('$bin' not on PATH); remediation: install the safe local coding agent stack (safe-agent install, or put the validated CLI on PATH; see data/openshell-colima-retest/report.md for the 0.1.10 binaries)" >&2
    return 1
  }
}

# fm_safe_agent_version_check: refuse loudly on a missing or older-than-floor
# openshell. Prints the resolved version on success.
fm_safe_agent_version_check() {
  local bin version rc
  bin=$(fm_safe_agent_openshell)
  fm_safe_agent_tool_check || return 1
  version=$("$bin" --version 2>/dev/null | awk '{print $2}')
  fm_safe_agent_version_at_least "$version" "$FM_SAFE_AGENT_MIN_OPENSHELL_VERSION"
  rc=$?
  case $rc in
    0) printf '%s\n' "$version" ;;
    1)
      echo "error: the safe-agent harness requires openshell >= $FM_SAFE_AGENT_MIN_OPENSHELL_VERSION (found ${version:-unparseable}); remediation: install the validated release binaries (see data/openshell-colima-retest/report.md)" >&2
      return 1 ;;
    *)
      echo "error: the safe-agent harness could not parse the installed openshell version ('$("$bin" --version 2>/dev/null)'); refusing on an unverifiable control plane" >&2
      return 1 ;;
  esac
}

# fm_safe_agent_gateway_state: classify `openshell status` the way the launcher
# does. Prints one of: connected\t<gateway-name> | disconnected | unreadable.
fm_safe_agent_gateway_state() {
  local bin out status gw
  bin=$(fm_safe_agent_openshell)
  out=$("$bin" status 2>&1) || { printf 'unreadable\n'; return 0; }
  status=$(printf '%s\n' "$out" | awk '/Status:/ { print tolower($2) }' | head -n 1)
  gw=$(printf '%s\n' "$out" | awk '/Gateway:/ { print $2 }' | head -n 1)
  case "$status" in
    connected) printf 'connected\t%s\n' "${gw:-unknown}" ;;
    disconnected|"") printf 'disconnected\n' ;;
    *) printf 'unreadable\n' ;;
  esac
}

# fm_safe_agent_gateway_ensure: refuse unless the launcher's gateway is
# connected. A connected foreign gateway is refused (the launcher's documented
# fail-loud case).
fm_safe_agent_gateway_ensure() {
  local state want
  fm_safe_agent_version_check >/dev/null || return 1
  state=$(fm_safe_agent_gateway_state)
  case "$state" in
    connected*) ;;
    disconnected)
      echo "error: the safe-agent harness refuses to launch: openshell reports no connected gateway (state: disconnected)" >&2
      echo "remediation: safe-agent up (bootstraps and registers the launcher's gateway); dispatch never falls back to unsandboxed execution" >&2
      return 1 ;;
    unreadable)
      echo "error: the safe-agent harness refuses to launch: the gateway state is unreadable (openshell status failed or was ambiguous)" >&2
      echo "remediation: openshell status; repair the gateway (safe-agent down && safe-agent up) before dispatching" >&2
      return 1 ;;
    *)
      echo "error: the safe-agent harness refuses to launch: gateway state '$state' is not the launcher's connected gateway" >&2
      return 1 ;;
  esac
  want=$(fm_safe_agent_config_get GATEWAY_NAME safe-agent)
  [ "${state#connected$'\t'}" = "$want" ] || {
    echo "error: the safe-agent harness refuses to launch: openshell is connected to gateway '${state#connected$'\t'}', not the launcher's gateway '$want'" >&2
    echo "remediation: adopt it explicitly (SAFE_AGENT_GATEWAY_NAME) or stop the foreign gateway, then safe-agent up" >&2
    return 1
  }
}

# fm_safe_agent_verify: the spawn-time installation check (binary present,
# version >= floor, gateway healthy), each refusal actionable. Prints a
# one-line summary on success.
fm_safe_agent_verify() {
  local version
  version=$(fm_safe_agent_version_check) || return 1
  fm_safe_agent_gateway_ensure || return 1
  printf 'safe-agent ready: openshell %s, gateway connected\n' "$version"
}

# fm_safe_agent_scoped_title <label>: the sandbox name a task gets,
# <home-label>-<label>, always within the pinned CLI's sandbox-name cap
# (live-reproduced refusal "name exceeds maximum length" on longer names). A
# label that does not fit is truncated to its leading characters plus a short
# cksum hash of the FULL label, so same-prefix labels stay distinguishable and
# home-scoping survives truncation.
fm_safe_agent_scoped_title() {  # <label>
  local home label hash budget trunc_len
  home=$(printf '%s' "$(fm_safe_agent_home)" | cksum | awk '{ print substr($1, 1, 4) }')
  home="fm${home}"
  label=$1
  budget=$(( FM_SAFE_AGENT_NAME_MAX - ${#home} - 1 ))
  if [ ${#label} -le "$budget" ]; then
    printf '%s-%s\n' "$home" "$label"
    return 0
  fi
  hash=$(printf '%s' "$label" | cksum | awk '{ print substr($1, 4) }' | awk '{ print substr($1, 1, 4) }')
  trunc_len=$(( budget - ${#hash} - 1 ))
  printf '%s-%.*s-%s\n' "$home" "$trunc_len" "$label" "$hash"
}

fm_safe_agent_sandbox_exists() {  # <name>
  local bin
  bin=$(fm_safe_agent_openshell)
  "$bin" sandbox get "$1" >/dev/null 2>&1
}

# fm_safe_agent_exchange_task_dir <label>: the task's exchange dir (firstmate
# records: boot.md, sandbox-name, runtime-log, status, output.log, inbox/).
fm_safe_agent_exchange_task_dir() {  # <label>
  local exchange_root
  exchange_root=$(fm_safe_agent_config_get EXCHANGE_ROOT) || return 1
  [ -n "$exchange_root" ] || return 1
  printf '%s/%s\n' "$exchange_root" "$1"
}

# fm_safe_agent_json_string VALUE: print VALUE escaped for use as the body of
# a JSON string literal. Refuses a control character - a configured path like
# that is a misconfiguration, and mangling it into the mount JSON would
# silently bind the wrong dir.
fm_safe_agent_json_string() {
  case $1 in
    *$'\n'*|*$'\r'*)
      echo "error: safe-agent driver config: path contains a newline or carriage return: '$1'" >&2
      return 1 ;;
  esac
  if printf '%s' "$1" | LC_ALL=C grep -q '[[:cntrl:]]'; then
    echo "error: safe-agent driver config: path contains a control character: '$1'" >&2
    return 1
  fi
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# fm_safe_agent_driver_config_json <worktree> <label>: the --driver-config-json
# value the create passes - the task worktree at /sandbox/worktree/<label>
# (below the image's workspace root, which itself refuses a mount), the
# exchange and scratch roots at their image paths, and the owning repository's
# git dir at /sandbox/gitcommon (the in-sandbox git enablement). Every source
# must be an absolute host path: docker would otherwise silently auto-create a
# missing source INSIDE the docker VM, which is exactly the container-local
# state this dispatch must never fall back to.
fm_safe_agent_driver_config_json() {  # <worktree> <label>
  local wt=$1 label=$2 ex sc gitdir wt_target je_wt je_target je_ex je_sc je_git
  wt_target="/sandbox/worktree/$label"
  ex=$(fm_safe_agent_config_get EXCHANGE_ROOT) || return 1
  sc=$(fm_safe_agent_config_get SCRATCH_ROOT) || return 1
  [ -n "$ex" ] && [ -n "$sc" ] || {
    echo "error: safe-agent launch requires EXCHANGE_ROOT and SCRATCH_ROOT; remediation: run safe-agent up && safe-agent firstmate" >&2
    return 1
  }
  gitdir=$(fm_safe_agent_git_common_dir "$wt") || return 1
  for src in "$wt" "$ex" "$sc" "$gitdir"; do
    case $src in
      /*) ;;
      *)
        echo "error: safe-agent driver config: bind source must be an absolute host path, got '$src'" >&2
        return 1 ;;
    esac
  done
  je_wt=$(fm_safe_agent_json_string "$wt") || return 1
  je_target=$(fm_safe_agent_json_string "$wt_target") || return 1
  je_ex=$(fm_safe_agent_json_string "$ex") || return 1
  je_sc=$(fm_safe_agent_json_string "$sc") || return 1
  je_git=$(fm_safe_agent_json_string "$gitdir") || return 1
  printf '{"docker":{"mounts":[{"type":"bind","source":"%s","target":"%s","read_only":false},{"type":"bind","source":"%s","target":"/sandbox/exchange","read_only":false},{"type":"bind","source":"%s","target":"/sandbox/scratch","read_only":false},{"type":"bind","source":"%s","target":"/sandbox/gitcommon","read_only":false}]}}' \
    "$je_wt" "$je_target" "$je_ex" "$je_sc" "$je_git"
}

# fm_safe_agent_git_common_dir <worktree>: the absolute git common dir that
# owns <worktree> (its .git dir for a plain checkout, its repository's .git for
# a linked worktree). Refuses when the worktree is not a git repository.
fm_safe_agent_git_common_dir() {  # <worktree>
  local wt=$1 common
  common=$(git -C "$wt" rev-parse --git-common-dir 2>/dev/null) || {
    echo "error: safe-agent launch: '$wt' is not a git repository (the crew works in the bound task worktree)" >&2
    return 1
  }
  case $common in
    /*) printf '%s\n' "$common" ;;
    *) (cd "$wt/$common" && pwd) ;;
  esac
}

# fm_safe_agent_git_env_values <worktree> <label>: print three lines for the
# create-time env that reattaches the bound git dir inside the sandbox:
# SAFE_AGENT_CREW_GIT_DIR (the linked worktree's own gitdir inside the bound
# common dir, or the bound common dir itself for a plain checkout),
# SAFE_AGENT_CREW_GIT_COMMON_DIR, and SAFE_AGENT_CREW_GIT_WORK_TREE.
fm_safe_agent_git_env_values() {  # <worktree> <label>
  local wt=$1 label=$2 common gitdir in_sandbox_common in_sandbox_gitdir
  common=$(fm_safe_agent_git_common_dir "$wt") || return 1
  gitdir=$(git -C "$wt" rev-parse --absolute-git-dir 2>/dev/null) || {
    echo "error: safe-agent launch: cannot resolve the git dir of '$wt'" >&2
    return 1
  }
  in_sandbox_common=/sandbox/gitcommon
  if [ "$gitdir" = "$common" ]; then
    in_sandbox_gitdir=$in_sandbox_common
  else
    case $gitdir in
      "$common"/*) ;;
      *)
        echo "error: safe-agent launch: the git dir of '$wt' ($gitdir) is not under its common dir ($common); refusing an unbindable layout" >&2
        return 1 ;;
    esac
    in_sandbox_gitdir="$in_sandbox_common/worktrees/${gitdir##*/}"
  fi
  printf 'SAFE_AGENT_CREW_GIT_DIR=%s\n' "$in_sandbox_gitdir"
  printf 'SAFE_AGENT_CREW_GIT_COMMON_DIR=%s\n' "$in_sandbox_common"
  printf 'SAFE_AGENT_CREW_GIT_WORK_TREE=/sandbox/worktree/%s\n' "$label"
}

# fm_safe_agent_seed_crew_config <provider> <endpoint-host> <base-url>
#   <profile-file> <cred-key>...: the seeded crew runtime config - the crew
#   permission profile with the model/provider configuration bound to the
#   ATTACHED provider merged in. Without the seed the runtime ignores the
#   attachment and calls its built-in default provider, which the crew policy
#   correctly refuses, and the crew then retries silently for its whole budget
#   (the pilot blocker fix). The merge is a real JSON parse, never a text
#   splice. Prints the merged JSON on stdout; refuses loudly on stderr.
fm_safe_agent_seed_crew_config() {  # <provider> <host> <base-url> <profile> <key>...
  local provider=$1 host=$2 base_url=$3 profile=$4
  shift 4
  command -v python3 >/dev/null 2>&1 || {
    echo "error: safe-agent launch: python3 not found (required to seed the crew runtime model/provider config)" >&2
    return 1
  }
  case $host in
    ''|*/*)
      echo "error: safe-agent launch: model endpoint must be a bare host, got '$host'" >&2
      return 1 ;;
  esac
  python3 - "$provider" "$host" "$base_url" "$profile" "$@" <<'PYEOF'
import json, sys

provider, host, base_url, profile = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
keys = sys.argv[5:]


def refuse(msg):
    sys.stderr.write("error: safe-agent launch: " + msg + "\n")
    sys.exit(1)


# The declared baseURL is seeded VERBATIM - never a synthesized path (the
# /v1 synthesis sent one provider's declared endpoint to a 405, pilot r3b).
# Containment guard: https only, a plain URL, and a host equal to the model
# endpoint host (the generated policy's model rule allows only that host).
if not base_url:
    refuse(
        "model base URL is required when a provider is attached (%s); "
        "remediation: set runtime.policy.model_base_url in safe-agent.toml "
        "and re-run safe-agent firstmate" % provider
    )
if not base_url.startswith("https://"):
    refuse(
        "model base URL must be an https URL (the sandbox containment layer "
        "never speaks plaintext), got '%s'" % base_url
    )
rest = base_url[len("https://"):]
if not rest or any(c.isspace() for c in base_url) or "?" in base_url or "#" in base_url:
    refuse("model base URL must be a plain https URL, got '%s'" % base_url)
base_host = rest.split("/", 1)[0]
if not base_host:
    refuse("model base URL must carry a host, got '%s'" % base_url)
if base_host.lower() != host.lower():
    refuse(
        "model base URL host '%s' does not match the model endpoint host '%s'; "
        "a mismatching baseURL would be policy-refused at call time"
        % (base_host, host)
    )


try:
    with open(profile, encoding="utf-8") as f:
        cfg = json.load(f)
except Exception as e:
    refuse("the crew runtime profile %s is not valid JSON (%s)" % (profile, e))
if not isinstance(cfg, dict):
    refuse("the crew runtime profile %s is not a JSON object" % profile)

ids = []
refs = [cfg.get("model")]
groups = cfg.get("model_groups")
if groups is not None and not isinstance(groups, dict):
    refuse("the crew runtime profile model_groups %r is not a JSON object" % (groups,))
if isinstance(groups, dict):
    refs.extend(groups.values())
for ref in refs:
    if ref is None:
        continue
    if not isinstance(ref, str):
        refuse("the crew runtime profile model ref %r is not a '<provider>/<model-id>' string" % (ref,))
    p, sep, m = ref.partition("/")
    if not sep or not m:
        refuse("the crew runtime profile model ref '%s' is not '<provider>/<model-id>'" % ref)
    if p != provider:
        refuse(
            "the crew runtime profile model ref '%s' targets provider '%s', not the "
            "attached provider '%s'; the crew would silently fall back to that "
            "provider's default model and stall" % (ref, p, provider)
        )
    if m not in ids:
        ids.append(m)
if not ids:
    refuse(
        "the crew runtime profile carries no model refs targeting the attached "
        "provider '%s'; set runtime.mimo.model_groups in safe-agent.toml and "
        "re-run safe-agent firstmate" % provider
    )
if not keys:
    refuse("the attached provider '%s' exposes no credential keys; cannot bind the model endpoint credential" % provider)

providers = cfg.get("provider")
if not isinstance(providers, dict):
    providers = {}
    cfg["provider"] = providers
# Complete per-model definitions (name + text modalities + limit) so the
# runtime's registry resolves them locally with no models.dev round-trip (the
# policy correctly refuses that catalog host; the values are the runtime's own
# unresolvable-metadata defaults).
providers[provider] = {
    "name": provider,
    "env": list(keys),
    "npm": "@ai-sdk/openai-compatible",
    "only_configured_models": True,
    "options": {"baseURL": base_url},
    "models": dict(
        (m, {
            "name": m,
            "modalities": {"input": ["text"], "output": ["text"]},
            "limit": {"context": 1000000, "output": 0},
        }) for m in ids
    ),
}
if cfg.get("model") is None:
    cfg["model"] = provider + "/" + ids[0]
json.dump(cfg, sys.stdout, indent=2)
sys.stdout.write("\n")
PYEOF
}

# fm_safe_agent_provider_credential_keys <provider-name>: the credential env
# key NAMES the attached provider exposes (never values), from the OpenShell
# provider registry.
fm_safe_agent_provider_credential_keys() {  # <provider-name>
  local out
  out=$("$(fm_safe_agent_openshell)" provider get "$1" 2>/dev/null) || {
    echo "error: safe-agent launch: openshell provider get $1 failed; cannot resolve the attached provider's credential keys (see openshell's error)" >&2
    return 1
  }
  printf '%s\n' "$out" | awk '/Credential keys:/ { sub(/^ *Credential keys: */, ""); print; exit }'
}

fm_safe_agent_main() {
  local mode=${1:-} label worktree name boot_dir resume create_envs
  case "$mode" in
    verify)
      fm_safe_agent_verify
      ;;
    config-get)
      shift
      [ -n "${1:-}" ] || { echo "error: config-get requires a KEY" >&2; return 2; }
      fm_safe_agent_config_get "$1"
      ;;
    launch)
      shift
      label=${1:-}
      worktree=${2:-}
      { [ -n "$label" ] && [ -n "$worktree" ]; } || {
        echo "error: launch requires <label> <worktree>" >&2
        return 2
      }
      [ -d "$worktree" ] || { echo "error: safe-agent launch: worktree $worktree does not exist" >&2; return 1; }
      fm_safe_agent_verify || return 1
      boot_dir=$(fm_safe_agent_exchange_task_dir "$label") || {
        echo "error: safe-agent launch: the exchange root is unset; remediation: run safe-agent up && safe-agent firstmate" >&2
        return 1
      }
      if [ ! -s "$boot_dir/boot.md" ]; then
        echo "error: safe-agent launch: the boot record $boot_dir/boot.md is missing or empty; bin/fm-spawn.sh writes it before launch - re-run the spawn" >&2
        return 1
      fi
      mkdir -p "$boot_dir/inbox" || { echo "error: safe-agent launch: cannot create $boot_dir/inbox" >&2; return 1; }
      name=$(fm_safe_agent_scoped_title "$label")
      resume=0
      if fm_safe_agent_sandbox_exists "$name"; then
        resume=1
        echo "safe-agent: reattaching to persisted sandbox $name (the boot record re-runs as the crew's instruction)"
      fi
      if [ "$resume" -eq 0 ]; then
        local driver_config git_env_line
        driver_config=$(fm_safe_agent_driver_config_json "$worktree" "$label") || return 1
        create_envs=(
          --env "SAFE_AGENT_CREW_TASK=$label"
          --env "SAFE_AGENT_CREW_FORMAT=$(fm_safe_agent_config_get CREW_FORMAT json)"
          --env "TMPDIR=/sandbox/scratch"
          --env "MIMOCODE_HOME=/sandbox/scratch/mimocode-home"
        )
        while IFS= read -r git_env_line; do
          create_envs+=(--env "$git_env_line")
        done < <(fm_safe_agent_git_env_values "$worktree" "$label")
        if ! "$(fm_safe_agent_openshell)" sandbox create \
          --name "$name" \
          --from "$(fm_safe_agent_config_get IMAGE)" \
          --policy "$(fm_safe_agent_config_get POLICY)" \
          "${create_envs[@]}" \
          --driver-config-json "$driver_config" \
          --label "openshell.ai/sandbox-attachable=true" \
          --detach; then
          echo "error: safe-agent launch: sandbox create refused for $name (see openshell's error above); a policy that omits a bind target (/sandbox/worktree/$label, /sandbox/exchange, /sandbox/scratch, /sandbox/gitcommon) is the common cause - add it to the crew policy and re-run safe-agent up" >&2
          return 1
        fi
      fi
      fm_safe_agent_dispatch_uploads "$name" "$label" "$resume" || return 1
      printf '%s\n' "$name" >"$boot_dir/sandbox-name" || {
        echo "error: safe-agent launch: cannot write $boot_dir/sandbox-name" >&2
        return 1
      }
      fm_safe_agent_exec_boot "$name" "$label" "$resume"
      ;;
    stop)
      shift
      label=${1:-}
      [ -n "$label" ] || { echo "error: stop requires <label>" >&2; return 2; }
      fm_safe_agent_stop "$label"
      ;;
    state)
      shift
      label=${1:-}
      [ -n "$label" ] || { echo "error: state requires <label>" >&2; return 2; }
      fm_safe_agent_state "$label"
      ;;
    *)
      echo "usage: fm-safe-agent-crew.sh verify|config-get KEY|launch <label> <worktree>|stop <label>|state <label>" >&2
      return 2
      ;;
  esac
}

# fm_safe_agent_dispatch_uploads <name> <label> <resume>: the create's upload
# sequence - stage, upload the boot wrapper, place and prove it, upload the
# boot record, and place the crew runtime permission profile (seeded when a
# provider is attached). The place-and-verify execs exist because the pinned
# CLI's `sandbox upload` lands the src under its own basename only when the
# dst is an EXISTING directory - a fresh dst is materialized as a file at the
# dst path itself - and because the boot launch is foreground, so a wrong
# artifact would swallow its own failure: each placement is proven before the
# next step runs.
fm_safe_agent_dispatch_uploads() {  # <name> <label> <resume>
  local name=$1 label=$2 resume=$3 bin boot_dir profile staging
  local seed_tmp="" seed_keys_raw
  bin=$(fm_safe_agent_openshell)
  boot_dir=$(fm_safe_agent_exchange_task_dir "$label") || return 1
  profile=$(fm_safe_agent_config_get MIMO_CONFIG "$(fm_safe_agent_home)/config/safe-agent-crew-mimocode.json")
  if [ ! -f "$profile" ]; then
    echo "error: safe-agent launch: crew runtime permission profile $profile not found; remediation: run safe-agent firstmate (emits it from [runtime.mimo] next to the backend env file)" >&2
    return 1
  fi
  local provider endpoint base_url
  provider=$(fm_safe_agent_config_get PROVIDER)
  if [ -n "$provider" ]; then
    endpoint=$(fm_safe_agent_config_get MODEL_ENDPOINT)
    base_url=$(fm_safe_agent_config_get MODEL_BASE_URL)
    [ -n "$endpoint" ] || {
      echo "error: safe-agent launch: FM_BACKEND_SANDBOX_MODEL_ENDPOINT is unset but a provider is attached ($provider); remediation: re-run safe-agent firstmate (re-emits the backend env file)" >&2
      return 1
    }
    [ -n "$base_url" ] || {
      echo "error: safe-agent launch: FM_BACKEND_SANDBOX_MODEL_BASE_URL is unset but a provider is attached ($provider); remediation: set runtime.policy.model_base_url in safe-agent.toml and re-run safe-agent firstmate" >&2
      return 1
    }
    seed_keys_raw=$(fm_safe_agent_provider_credential_keys "$provider") || return 1
    case $seed_keys_raw in
      ''|'<none>')
        echo "error: safe-agent launch: the attached provider $provider exposes no credential keys; cannot seed the crew runtime's model/provider config" >&2
        return 1 ;;
    esac
    # deliberate word-splitting: the key list is a space-separated set of
    # credential env NAMES passed as one argument each.
    # shellcheck disable=SC2086
    seed_tmp=$(mktemp "${TMPDIR:-/tmp}/fm-safe-agent-seed.XXXXXX")
    # shellcheck disable=SC2086
    if ! fm_safe_agent_seed_crew_config "$provider" "$endpoint" "$base_url" "$profile" $seed_keys_raw >"$seed_tmp"; then
      rm -f "$seed_tmp"
      return 1
    fi
  fi
  staging="/sandbox/scratch/$label"
  if ! "$bin" sandbox exec -n "$name" -- /bin/sh -c 'mkdir -p "$0"' "$staging"; then
    echo "error: safe-agent launch: cannot create the staging dir $staging in $name" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if ! "$bin" sandbox upload --no-git-ignore "$name" \
    "$_FM_SAFE_AGENT_LIB_DIR/fm-safe-agent-crew-boot.sh" "$staging"; then
    echo "error: safe-agent launch: boot wrapper upload refused for $name" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if ! "$bin" sandbox exec -n "$name" -- \
    /bin/sh -c 'mv "$0" "$1" && chmod 0755 "$1" && test -f "$1" && test -x "$1"' \
    "$staging/fm-safe-agent-crew-boot.sh" /sandbox/scratch/safe-agent-crew-boot; then
    echo "error: safe-agent launch: the boot wrapper did not land as a regular executable in $name; remediation: openshell sandbox delete $name, then re-run the spawn" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if ! "$bin" sandbox upload --no-git-ignore "$name" "$boot_dir/boot.md" "$staging"; then
    echo "error: safe-agent launch: boot record upload refused for $name" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if ! "$bin" sandbox exec -n "$name" -- \
    /bin/sh -c 'mv "$0" "$1" && test -f "$1"' \
    "$staging/boot.md" "/sandbox/scratch/$label-boot.md"; then
    echo "error: safe-agent launch: the boot record did not land in $name; remediation: openshell sandbox delete $name, then re-run the spawn" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if ! "$bin" sandbox exec -n "$name" -- \
    /bin/sh -c 'mkdir -p "$0"' /sandbox/scratch/mimocode-home/config; then
    echo "error: safe-agent launch: cannot create the crew profile dir in $name" >&2
    [ -z "$seed_tmp" ] || rm -f "$seed_tmp"
    return 1
  fi
  if [ -n "$seed_tmp" ]; then
    if ! "$bin" sandbox upload --no-git-ignore "$name" "$seed_tmp" "$staging"; then
      echo "error: safe-agent launch: seeded crew profile upload refused for $name" >&2
      rm -f "$seed_tmp"
      return 1
    fi
    if ! "$bin" sandbox exec -n "$name" -- \
      /bin/sh -c 'mv "$0" "$1" && test -f "$1"' \
      "$staging/$(basename "$seed_tmp")" /sandbox/scratch/mimocode-home/config/mimocode.json; then
      echo "error: safe-agent launch: the seeded crew profile did not land in $name; remediation: openshell sandbox delete $name, then re-run the spawn" >&2
      rm -f "$seed_tmp"
      return 1
    fi
    rm -f "$seed_tmp"
  else
    if ! "$bin" sandbox upload --no-git-ignore "$name" "$profile" "$staging"; then
      echo "error: safe-agent launch: crew profile upload refused for $name" >&2
      return 1
    fi
    if ! "$bin" sandbox exec -n "$name" -- \
      /bin/sh -c 'mv "$0" "$1" && test -f "$1"' \
      "$staging/$(basename "$profile")" /sandbox/scratch/mimocode-home/config/mimocode.json; then
      echo "error: safe-agent launch: the crew profile did not land in $name; remediation: openshell sandbox delete $name, then re-run the spawn" >&2
      return 1
    fi
  fi
  return 0
}

# fm_safe_agent_exec_boot <name> <label>: the crew boot launch - the wrapper in
# the FOREGROUND of `sandbox exec --tty`, so the pane carries the streamed crew
# session while it works and drops back to its shell when the wrapper exits.
# The runtime allocates the pty outside the sandbox and keeps the session
# alive across client disconnects (live-verified on the pinned CLI), which is
# why a killed pane never means a stopped crew - stop goes through `stop`
# (sandbox delete), never through the pane.
fm_safe_agent_exec_boot() {  # <name> <label>
  local name=$1 label=$2 bin rc=0
  bin=$(fm_safe_agent_openshell)
  "$bin" sandbox exec --tty -n "$name" -- \
    /bin/sh -c 'exec "$0" "$1" "$2"' \
    /sandbox/scratch/safe-agent-crew-boot "$label" "$3" || rc=$?
  return "$rc"
}

# fm_safe_agent_stop <label>: idempotent sandbox delete - the control plane's
# stop primitive. Refuses (never claims stopped) when the gateway cannot
# answer, and is silent success when the sandbox is already gone.
fm_safe_agent_stop() {  # <label>
  local label=$1 bin name boot_dir recorded
  bin=$(fm_safe_agent_openshell)
  fm_safe_agent_tool_check || return 1
  name=$(fm_safe_agent_scoped_title "$label")
  boot_dir=$(fm_safe_agent_exchange_task_dir "$label") 2>/dev/null || boot_dir=
  if [ -n "$boot_dir" ] && [ -f "$boot_dir/sandbox-name" ]; then
    recorded=$(cat "$boot_dir/sandbox-name" 2>/dev/null)
    [ -n "$recorded" ] && [ "$recorded" != "$name" ] && name=$recorded
  fi
  case "$(fm_safe_agent_gateway_state)" in
    connected*) ;;
    *)
      echo "error: safe-agent stop refuses: the gateway state is not connected (delete is the only stop primitive, and an unreachable gateway cannot prove it); remediation: repair the gateway (safe-agent down && safe-agent up), then retry" >&2
      return 1 ;;
  esac
  if ! fm_safe_agent_sandbox_exists "$name"; then
    return 0
  fi
  "$bin" sandbox delete "$name" || {
    echo "error: safe-agent stop: sandbox delete failed for $name (see openshell's error above); remove it by hand with 'openshell sandbox delete $name'" >&2
    return 1
  }
}

# fm_safe_agent_state <label>: recovery-grade crew state. Prints
# alive|dead|missing|unreadable. A gateway that cannot answer is `unreadable`,
# never inferred absence; the sandbox's existence is proven through the
# gateway (`sandbox get`) and the boot process through an in-sandbox pgrep.
fm_safe_agent_state() {  # <label>
  local label=$1 bin name out
  bin=$(fm_safe_agent_openshell)
  fm_safe_agent_tool_check || { printf 'unreadable'; return 0; }
  name=$(fm_safe_agent_scoped_title "$label")
  if ! out=$("$bin" sandbox get "$name" 2>&1); then
    case "$out" in
      *not*found*|*NotFound*|*does*not*exist*) printf 'missing' ;;
      *) printf 'unreadable' ;;
    esac
    return 0
  fi
  case "$(fm_safe_agent_gateway_state)" in
    connected*) ;;
    *) printf 'unreadable'; return 0 ;;
  esac
  if "$bin" sandbox exec -n "$name" -- \
    /bin/sh -c 'pgrep -f safe-agent-crew-boot >/dev/null 2>&1 && echo alive || echo dead' 2>/dev/null |
    grep -q alive; then
    printf 'alive'
  else
    printf 'dead'
  fi
}

