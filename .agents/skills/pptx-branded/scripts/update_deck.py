#!/usr/bin/env python3
"""update_deck.py — diff-based update of a generated deck.

Rule (captain decision Q3): every slide NOT marked `pinned` is regenerated on
update; a manual touch-up survives only by marking its slide `pinned` in the
deck-spec.

Usage: update_deck.py <deck.pptx> <new-deck-spec.json> [--manifest <path>]

The deck must have been generated by build_deck.py (manifest sits next to it,
`<deck>-manifest.json`).

Behavior, position by position (new spec index i vs old manifest entry i):
  - entree identical and spec hash identical -> slide left untouched.
  - entree identical, hash differs, not pinned -> zones/placeholders re-applied
    in place on the existing slide (geometry preserved).
  - old entry pinned -> slide kept as-is (warning printed).
  - spec longer than deck -> new slides generated from the template, appended.
  - deck longer than spec -> trailing slides deleted unless pinned.
  - entree CHANGED at any position -> refused (fail-safe): rebuild instead with
    build_deck.py, since in-place re-cloning would corrupt position semantics.
"""
import hashlib, json, os, sys
from pptx import Presentation

from build_deck import clone_slide, set_zone, resolve_shape, find_layout


def entry_hash(entry):
    body = {k: v for k, v in entry.items() if k != "pinned"}
    return hashlib.sha1(json.dumps(body, sort_keys=True).encode()).hexdigest()


def reapply(slide, entry):
    kind, _, ref = entry["entree"].partition(":")
    if kind == "motif":
        for key, zone in (entry.get("zones") or {}).items():
            match = zone.get("match") if isinstance(zone, dict) else None
            sh = resolve_shape(slide, key, match)
            if sh is None:
                print(f"WARN: zone {key!r} introuvable")
                continue
            set_zone(sh, zone)
    elif kind == "layout":
        for idx, text in (entry.get("placeholders") or {}).items():
            idx = int(idx)
            for sh in slide.placeholders:
                if sh.placeholder_format.idx == idx:
                    sh.text_frame.text = text
                    break


def delete_slide(prs, pos):
    sldIdLst = prs.slides._sldIdLst
    sldId = list(sldIdLst)[pos]
    sldIdLst.remove(sldId)
    prs.part.drop_rel(sldId.rId)


def main(deck_path, spec_path, manifest_path=None):
    spec = json.load(open(spec_path))
    if manifest_path is None:
        manifest_path = os.path.splitext(deck_path)[0] + "-manifest.json"
    manifest = json.load(open(manifest_path))
    old = manifest["slides"]
    new_entries = spec["slides"]

    conflicts = [i for i in range(min(len(old), len(new_entries)))
                 if old[i]["entree"] != new_entries[i]["entree"]]
    if conflicts:
        raise SystemExit(
            f"entree modifiée aux positions {conflicts} — update in situ impossible; "
            "reconstruire avec build_deck.py (les slides pinned doivent être "
            "recopiées manuellement ou re-spécifiées).")

    prs = Presentation(deck_path)
    deck_slides = list(prs.slides)
    n_changed = n_kept = n_pinned = 0

    for i, entry in enumerate(new_entries):
        if i >= len(deck_slides):
            break
        if old[i]["pinned"] or entry.get("pinned"):
            print(f"slide {i}: pinned — inchangée")
            n_pinned += 1
            continue
        if old[i]["hash"] == entry_hash(entry):
            n_kept += 1
            continue
        reapply(deck_slides[i], entry)
        note = (spec.get("notes") or {}).get(str(i))
        if note:
            deck_slides[i].notes_slide.notes_text_frame.text = note
        n_changed += 1
        print(f"slide {i}: zones réappliquées")

    # appended slides
    if len(new_entries) > len(deck_slides):
        for i in range(len(deck_slides), len(new_entries)):
            entry = new_entries[i]
            kind, _, ref = entry["entree"].partition(":")
            if kind == "layout":
                s = prs.slides.add_slide(find_layout(prs, ref))
                for idx, text in (entry.get("placeholders") or {}).items():
                    idx = int(idx)
                    for sh in s.placeholders:
                        if sh.placeholder_format.idx == idx:
                            sh.text_frame.text = text
                            break
            elif kind == "motif":
                # cloning needs the template slides in this package; they were
                # pruned at build time — a full rebuild is the safe path
                raise SystemExit(
                    "ajout d'une slide motif sur un deck existant non supporté "
                    "en v1 (le template n'est plus dans le paquet) — "
                    "reconstruire avec build_deck.py.")
            note = (spec.get("notes") or {}).get(str(i))
            if note:
                s.notes_slide.notes_text_frame.text = note
            n_changed += 1
            print(f"slide {i}: ajoutée")

    # removed trailing slides — reverse order, indices shift on each delete
    for i in range(len(deck_slides) - 1, len(new_entries) - 1, -1):
        if old[i]["pinned"]:
            print(f"slide {i}: pinned — conservée malgré le retrait du spec")
            continue
        delete_slide(prs, i)
        n_changed += 1
        print(f"slide {i}: supprimée")

    prs.save(deck_path)
    # refresh manifest
    import time
    manifest["updated_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    manifest["slides"] = [{"index": i, "entree": e["entree"],
                           "pinned": bool(e.get("pinned", False)),
                           "hash": entry_hash(e), "spec_entry": e}
                          for i, e in enumerate(new_entries)]
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)
    print(f"saved {deck_path}: {n_changed} modifiées, {n_kept} inchangées, {n_pinned} pinned")


if __name__ == "__main__":
    args = sys.argv[1:]
    mflag = "--manifest"
    manifest = None
    if mflag in args:
        p = args.index(mflag)
        manifest = args[p + 1]
        del args[p:p + 2]
    main(args[0], args[1], manifest)
